use std::io::Write;

use super::*;
use crate::{DependencyScope, FileType, RefKind, RefLocator};

const PKGINFO: &[u8] = b"# Generated by makepkg\npkgname = demo\npkgver = 1:2.0-3\nurl = https://example.test/demo\nlicense = MIT\nlicense = Apache-2.0\ndepend = bash>=5\noptdepend = electron: graphical interface\nmakedepend = nodejs\n";

fn tar_of(name: &str, data: &[u8]) -> Vec<u8> {
    let mut tar = tar::Builder::new(Vec::new());
    let mut header = tar::Header::new_gnu();
    header.set_size(data.len() as u64);
    header.set_mode(0o644);
    header.set_cksum();
    tar.append_data(&mut header, name, data).unwrap();
    tar.into_inner().unwrap()
}

/// Every compression makepkg offers reads to the same `pkg.*` fields.
fn compressed(plain: &[u8]) -> [Vec<u8>; 4] {
    let zstd = zstd::stream::encode_all(plain, 1).unwrap();
    let mut gz = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::fast());
    gz.write_all(plain).unwrap();
    let mut xz =
        lzma_rust2::XzWriter::new(Vec::new(), lzma_rust2::XzOptions::with_preset(1)).unwrap();
    xz.write_all(plain).unwrap();
    [
        plain.to_vec(),
        zstd,
        gz.finish().unwrap(),
        xz.finish().unwrap(),
    ]
}

#[test]
fn pkginfo_lands_in_the_pkgbuild_vocabulary() {
    for bytes in compressed(&tar_of(".PKGINFO", PKGINFO)) {
        let mut values = Values::new();
        extract(&bytes, &mut values);
        assert_eq!(values.get("pkg.pkgname"), Some(&"demo".into()));
        assert_eq!(values.get("pkg.epoch"), Some(&"1".into()));
        assert_eq!(values.get("pkg.pkgver"), Some(&"2.0".into()));
        assert_eq!(values.get("pkg.pkgrel"), Some(&"3".into()));
        assert_eq!(
            values.get("pkg.license"),
            Some(&serde_json::json!(["MIT", "Apache-2.0"]))
        );
        assert_eq!(
            values.get("pkg.depends"),
            Some(&serde_json::json!(["bash>=5"]))
        );
    }
}

#[test]
fn package_dependencies_carry_scope_optionality_and_requirement() {
    for bytes in compressed(&tar_of(".PKGINFO", PKGINFO)) {
        let mut values = Values::new();
        extract(&bytes, &mut values);
        let refs = crate::formats::references::derive(FileType::PkgArch, &bytes, &values);
        let find = |name: &str| {
            refs.iter()
                .find(|r| matches!(&r.locator, RefLocator::Purl(p) if p.starts_with(name)))
                .unwrap_or_else(|| panic!("{name}: {refs:?}"))
        };
        let bash = find("pkg:alpm/arch/bash?");
        assert!(matches!(&bash.locator, RefLocator::Purl(p) if p.contains("version_requirement=")));
        assert_eq!(bash.kind, RefKind::Dependency);
        assert!(!bash.context.as_ref().unwrap().optional);
        let electron = find("pkg:alpm/arch/electron");
        assert!(electron.context.as_ref().unwrap().optional);
        assert_eq!(
            find("pkg:alpm/arch/nodejs").context.as_ref().unwrap().scope,
            DependencyScope::Build
        );
        assert_eq!(refs.len(), 3, "{refs:?}");
    }
}

#[test]
fn a_package_without_pkginfo_has_no_package_fields() {
    let mut values = Values::new();
    extract(&tar_of("usr/bin/demo", b"#!/bin/sh\n"), &mut values);
    assert!(values.get("pkg").is_none());
    extract(b"not a package", &mut values);
    assert!(values.get("pkg").is_none());
}

#[test]
fn an_oversized_pkginfo_is_skipped() {
    let big = vec![b'x'; usize::try_from(MAX_PKGINFO_BYTES).unwrap() + 1];
    let mut values = Values::new();
    extract(&tar_of(".PKGINFO", &big), &mut values);
    assert!(values.get("pkg").is_none());
}
