//! The Python 2 names CPython's unpickler renames before importing.
//!
//! Below protocol 3, `Unpickler.find_class` (and the C `_pickle` module)
//! looks `(module, name)` up in `_compat_pickle.NAME_MAPPING`, and failing
//! that `module` in `_compat_pickle.IMPORT_MAPPING`, and imports what it
//! finds there. These are those tables as CPython 3.12 ships them,
//! including the `exceptions.WindowsError` entry it adds on Windows.

/// The `(module, name)` CPython imports for a global a pickle of
/// `protocol` names as `module.name`. A stream without a PROTO opcode
/// (`None`) is protocol 0.
pub(super) fn find_class<'a>(
    protocol: Option<u8>,
    module: &'a str,
    name: &'a str,
) -> (&'a str, &'a str) {
    if protocol.is_some_and(|p| p >= 3) {
        return (module, name);
    }
    if let Some(renamed) = name_mapping(module, name) {
        return renamed;
    }
    (import_mapping(module).unwrap_or(module), name)
}

